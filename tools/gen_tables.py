#!/usr/bin/env python3
"""Generates src/present_tables.h: PRESENT lookup tables that live in Flash (PROGMEM)."""
import os
import sys

S = [0xC, 0x5, 0x6, 0xB, 0x9, 0x0, 0xA, 0xD, 0x3, 0xE, 0xF, 0x8, 0x4, 0x7, 0x1, 0x2]
SI = [S.index(i) for i in range(16)]

# S-box applied to both nibbles of a byte (one LPM instead of two)
sbox8 = [(S[v >> 4] << 4) | S[v & 15] for v in range(256)]
sbox8_inv = [(SI[v >> 4] << 4) | SI[v & 15] for v in range(256)]

# pLayer helper. State = 16 nibbles; the pLayer is a 4x16 bit transposition:
#   output bit (16*q + r)  <-  input bit (4*r + q)
# For one input byte v (nibbles r=2a, 2a+1) the table packs, for every q = 0..3,
# the 2-bit field  bit_q(low nibble) | bit_q(high nibble) << 1  at bits 2q..2q+1.
pl = []
for v in range(256):
    t = 0
    for q in range(4):
        c = ((v >> q) & 1) | (((v >> (q + 4)) & 1) << 1)
        t |= c << (2 * q)
    pl.append(t)

# Textbook bit permutation for the naive variant: bit i moves to pbox[i]
pbox = [63 if i == 63 else (16 * i) % 63 for i in range(64)]


def emit(name, vals, per=16):
    lines = ["static const uint8_t %s[%d] PROGMEM PRESENT_UNUSED = {" % (name, len(vals))]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join("0x%02X" % x for x in vals[i:i + per]) + ",")
    lines.append("};\n")
    return "\n".join(lines)


out = ["/* Generated by tools/gen_tables.py - do not edit. */",
       "#ifndef PRESENT_TABLES_H", "#define PRESENT_TABLES_H",
       "#include <stdint.h>", "#include <avr/pgmspace.h>", "",
       "#define PRESENT_UNUSED __attribute__((unused))", ""]
out.append(emit("PRESENT_SBOX4", S))
out.append(emit("PRESENT_SBOX4_INV", SI))
out.append(emit("PRESENT_SBOX8", sbox8))
out.append(emit("PRESENT_SBOX8_INV", sbox8_inv))
out.append(emit("PRESENT_PL", pl))
out.append(emit("PRESENT_PBOX", pbox))
out.append("#endif\n")

here = os.path.dirname(os.path.abspath(__file__))
dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "src", "present_tables.h")
with open(dest, "w") as f:
    f.write("\n".join(out))
print("wrote", os.path.normpath(dest))
